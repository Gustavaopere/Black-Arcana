#!/usr/bin/env python3
"""Verify seven injected handler INVOKEs in exported minimal-server Mixin targets.

Uses javap on actual .mixin.out/class files generated by the server bootstrap.
This checks callsite *presence and owner/descriptor* in the expected target
methods. It does NOT exercise handlers with player movement, full modpack,
slime spell/boots, networking or any writeable perk interface.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import unittest

from minecraft_1211_vanilla_target_callsites import CALL, exact_method
from vanillabackport_11710_postmixin_export import CLASSES

TARGETS = {
    "Entity": {
        "java_class":"net.minecraft.world.entity.Entity",
        "methods":{
            "move":("(Lnet/minecraft/world/entity/MoverType;Lnet/minecraft/world/phys/Vec3;)V",[
                ("handler","$vanillabackport$vb$earlyCapture"),
                ("wrapOperation","$vanillabackport$vb$capture"),
                ("handler","$vanillabackport$vb$RestituteMovementAfterCollisions"),
            ])
        }
    },
    "LivingEntity": {
        "java_class":"net.minecraft.world.entity.LivingEntity",
        "methods":{
            "createLivingAttributes":("()Lnet/minecraft/world/entity/ai/attributes/AttributeSupplier$Builder;",[
                ("modifyReturnValue","$vanillabackport$createLivingAttributes"),
            ]),
            "travel":("(Lnet/minecraft/world/phys/Vec3;)V",[
                ("modify","$vanillabackport$vb$handleMovementFriction"),
                ("wrapOperation","$vanillabackport$vb$applyAirDrag"),
            ]),
        }
    },
    "RangedAttribute": {
        "java_class":"net.minecraft.world.entity.ai.attributes.RangedAttribute",
        "methods":{
            "RangedAttribute":("(Ljava/lang/String;DDD)V",[
                ("handler","$vanillabackport$vb$fixKnockbackResistanceRange"),
            ])
        }
    }
}
HEADER = re.compile(r"^  .+\([^;]*\);$")
DESC = re.compile(r"^    descriptor: (\S+)$")

def method_declarations(javap_output: str):
    lines=javap_output.splitlines()
    found={}
    for i,line in enumerate(lines[:-1]):
        if not HEADER.match(line): continue
        descriptor=DESC.fullmatch(lines[i+1])
        if descriptor is None: continue
        name=line.strip().split("(",1)[0].split()[-1]
        found.setdefault(name,[]).append(descriptor.group(1))
    return found

def exact_handler(declarations:dict, family:str, suffix:str):
    options=[(name,desc[0]) for name,desc in declarations.items()
             if name.startswith(family+"$") and name.endswith(suffix)
             and len(desc)==1]
    if len(options)!=1:
        raise ValueError("POSTMIXIN_HANDLER_DECLARATION_MISSING_OR_DUPLICATE:"+
                         suffix+":count="+str(len(options)))
    return options[0]

def scoped_calls(lines:list[str],name:str,descriptor:str,owner_internal:str):
    matched=[]
    for line in lines:
        x=CALL.match(line)
        if x is None:continue
        if x["name"]!=name or x["desc"]!=descriptor:continue
        if x["owner"] is not None and x["owner"]!=owner_internal:continue
        matched.append({"pc":int(x.group(1)),"opcode":x.group(2)})
    return matched

def analyze_class(label:str,output:str):
    entry=TARGETS[label]
    declarations=method_declarations(output)
    spec=entry["methods"]
    result={}
    for owner_method,(desc,handlers) in spec.items():
        caller=exact_method(output,owner_method,desc)
        hits=[]
        for family,suffix in handlers:
            handler,handler_desc=exact_handler(declarations,family,suffix)
            found=scoped_calls(caller,handler,handler_desc,
                               entry["java_class"].replace(".","/"))
            if len(found)!=1:
                raise ValueError("POSTMIXIN_HANDLER_INVOKE_CARDINALITY_DRIFT:"+
                                 label+"::"+owner_method+":"+suffix+
                                 ":calls="+str(len(found)))
            hits.append({
                "handler_suffix":suffix,"handler_name":handler,
                "handler_descriptor":handler_desc,
                "target_method":owner_method,"target_descriptor":desc,
                "invoke_pc":found[0]["pc"],"invoke_opcode":found[0]["opcode"],
                "declared_in_exported_class":True,
                "invoked_from_expected_exported_method_exactly_once":True
            })
        result[owner_method]=hits
    return result

def verify(root:Path):
    export=root/".mixin.out"/"class"
    reports={}
    for label,rel in CLASSES.items():
        file=export/rel
        if not file.is_file(): raise ValueError("POSTMIXIN_EXPORT_MISSING:"+rel)
        raw=file.read_bytes()
        if len(raw)<150 or raw[:4]!=bytes.fromhex("cafebabe"):
            raise ValueError("POSTMIXIN_EXPORT_INVALID_CLASS:"+rel)
        name=TARGETS[label]["java_class"]
        javap=subprocess.run(
            ["javap","-p","-c","-s","-classpath",str(export),name],
            text=True,capture_output=True,check=True).stdout
        reports[label]={
            "export_class":rel,
            "sha256":hashlib.sha256(raw).hexdigest(),
            "bytes":len(raw),
            "verified_target_method_injections":analyze_class(label,javap),
        }
    count=sum(len(hits) for value in reports.values()
              for hits in value["verified_target_method_injections"].values())
    if count!=7:raise ValueError("POSTMIXIN_HANDLER_TOTAL_DRIFT:"+str(count))
    return {
        "status":"PASS_VB_11710_MINIMAL_POSTMIXIN_HANDLER_INVOKE_LINKAGE",
        "evidence_class":"EXPORTED_POST_MIXIN_CLASSFILE_BOUNDED_CALLSITE_LINKAGE",
        "environment":"NeoForge 21.1.250, Platform 1.3.3, Vanilla Backport 1.1.7.10, isolated dedicated server",
        "handlers_verified":count,
        "exported_classes":reports,
        "runtime_callbacks_exercised":"NOT_TESTED",
        "full_modpack_compatibility":"NOT_TESTED",
        "limits":[
            "Only handlers actually present in exported classes and direct caller linkage were checked.",
            "No Minecraft physical player movement or actual handler execution proven.",
            "No Iron's Spellbooks/Backported Spellbooks/Epic Fight/full modpack loaded.",
            "No NeoForge client, connected player, configured attributes, world data or third-party perk API.",
            "Mixin export is a diagnostic; transformed bytes must not be packaged or distributed."
        ],
        "deviations":[]
    }

class Regression(unittest.TestCase):
    def test_typed_synthetic_handler_link(self):
        o=('  public void travel(net.minecraft.world.phys.Vec3);\n'
           '    descriptor: (Lnet/minecraft/world/phys/Vec3;)V\n'
           '    Code:\n'
           '       7: invokespecial #13 // Method wrapOperation$test$vanillabackport$vb$applyAirDrag:(D)V\n'
           '\n'
           '  private void wrapOperation$test$vanillabackport$vb$applyAirDrag(double);\n'
           '    descriptor: (D)V\n'
           '}')
        decl=method_declarations(o)
        name,desc=exact_handler(decl,"wrapOperation","$vanillabackport$vb$applyAirDrag")
        self.assertEqual(scoped_calls(
            exact_method(o,"travel","(Lnet/minecraft/world/phys/Vec3;)V"),
            name,desc,"net/minecraft/world/entity/LivingEntity"),
            [{"pc":7,"opcode":"invokespecial"}])
    def test_missing_handler_fails(self):
        with self.assertRaisesRegex(ValueError,"POSTMIXIN_HANDLER_DECLARATION"):
            exact_handler({},"handler","$vanillabackport$vb$earlyCapture")
    def test_duplicate_handler_fails(self):
        with self.assertRaisesRegex(ValueError,"POSTMIXIN_HANDLER_DECLARATION"):
            exact_handler({
                "handler$one$vanillabackport$vb$earlyCapture":["()V"],
                "handler$two$vanillabackport$vb$earlyCapture":["()V"],
            },"handler","$vanillabackport$vb$earlyCapture")
    def test_wrong_owner_rejected(self):
        lines=[" 1: invokespecial #13 // Method other/Class.handler$x$vanillabackport$vb$earlyCapture:()V"]
        self.assertEqual(scoped_calls(lines,"handler$x$vanillabackport$vb$earlyCapture",
                                      "()V","net/minecraft/world/entity/Entity"),[])
    def test_wrong_descriptor_rejected(self):
        lines=[" 1: invokespecial #13 // Method handler$x$vanillabackport$vb$earlyCapture:(F)V"]
        self.assertEqual(scoped_calls(lines,"handler$x$vanillabackport$vb$earlyCapture",
                                      "(D)V","net/minecraft/world/entity/Entity"),[])
    def test_expected_exact_scope(self):
        self.assertEqual(len(TARGETS),3)
        self.assertEqual(sum(len(x) for v in TARGETS.values()
                for _,x in v["methods"].values()),7)
    def test_missing_export_fails(self):
        from tempfile import TemporaryDirectory
        with TemporaryDirectory() as d:
            with self.assertRaisesRegex(ValueError,"POSTMIXIN_EXPORT_MISSING"):
                verify(Path(d))

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--self-test",action="store_true")
    ap.add_argument("--root",type=Path)
    ap.add_argument("--output",type=Path)
    args=ap.parse_args()
    if args.self_test:
        r=unittest.TextTestRunner(verbosity=2).run(
            unittest.defaultTestLoader.loadTestsFromTestCase(Regression))
        return 0 if r.wasSuccessful() else 1
    if not args.root or not args.output:ap.error("--root and --output required")
    try:
        result=verify(args.root)
    except (OSError,ValueError,subprocess.CalledProcessError) as e:
        result={"status":"FAIL_CLOSED_POSTMIXIN_INVOKE_GATE","deviations":[str(e)]}
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,sort_keys=True,indent=2)+"\n",encoding="utf-8")
    print(json.dumps({"status":result["status"],"verified":result.get("handlers_verified"),
                      "deviations":result["deviations"]}))
    return 0 if result["status"]=="PASS_VB_11710_MINIMAL_POSTMIXIN_HANDLER_INVOKE_LINKAGE" else 2

if __name__=="__main__":sys.exit(main())
